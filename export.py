"""
DOCX export module.

Generates a professionally formatted Word document from the
final chapter list.
"""

import logging
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

import config

logger = logging.getLogger(__name__)


def _extract_title(concept: str) -> str:
    """Pull the book title from the concept text."""
    for line in concept.split("\n"):
        upper = line.strip().upper()
        if upper.startswith("TITLE:"):
            return line.split(":", 1)[1].strip()
    return "Untitled Novel"


def _extract_subtitle(concept: str) -> str:
    """Pull the subtitle/tagline if present."""
    for line in concept.split("\n"):
        upper = line.strip().upper()
        if upper.startswith("SUBTITLE:"):
            return line.split(":", 1)[1].strip()
    return ""


def export_docx(
    chapters: list[str],
    concept: str,
    output_dir: str | None = None,
) -> Path:
    """
    Generate a formatted DOCX manuscript.

    Parameters
    ----------
    chapters : list[str]
        Final polished chapter texts.
    concept : str
        Story concept (used to extract title).
    output_dir : str, optional
        Output directory. Defaults to config.OUTPUT_DIR.

    Returns
    -------
    Path
        Absolute path to the generated .docx file.
    """
    out_dir = Path(output_dir or config.OUTPUT_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)

    title = _extract_title(concept)
    subtitle = _extract_subtitle(concept)

    doc = Document()

    # ── Document styles ───────────────────────────────────────────────────
    style = doc.styles["Normal"]
    font = style.font
    font.name = "Georgia"
    font.size = Pt(12)
    font.color.rgb = RGBColor(0x1A, 0x1A, 0x1A)

    paragraph_format = style.paragraph_format
    paragraph_format.space_after = Pt(6)
    paragraph_format.line_spacing = 1.5

    # ── Title page ────────────────────────────────────────────────────────
    for _ in range(6):
        doc.add_paragraph("")

    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_para.add_run(title)
    title_run.bold = True
    title_run.font.size = Pt(28)
    title_run.font.color.rgb = RGBColor(0x2C, 0x3E, 0x50)

    if subtitle:
        sub_para = doc.add_paragraph()
        sub_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        sub_run = sub_para.add_run(subtitle)
        sub_run.italic = True
        sub_run.font.size = Pt(16)
        sub_run.font.color.rgb = RGBColor(0x7F, 0x8C, 0x8D)

    doc.add_paragraph("")
    doc.add_paragraph("")

    gen_para = doc.add_paragraph()
    gen_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    gen_run = gen_para.add_run("Generated by Novel Writer Agent")
    gen_run.font.size = Pt(10)
    gen_run.font.color.rgb = RGBColor(0xBD, 0xBD, 0xBD)

    date_para = doc.add_paragraph()
    date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    date_run = date_para.add_run(datetime.now().strftime("%B %d, %Y"))
    date_run.font.size = Pt(10)
    date_run.font.color.rgb = RGBColor(0xBD, 0xBD, 0xBD)

    # ── Chapters ──────────────────────────────────────────────────────────
    total_words = 0

    for i, chapter_text in enumerate(chapters, 1):
        doc.add_page_break()

        # Chapter heading
        heading = doc.add_heading(f"Chapter {i}", level=1)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for run in heading.runs:
            run.font.color.rgb = RGBColor(0x2C, 0x3E, 0x50)

        doc.add_paragraph("")  # spacing

        # Chapter body
        paragraphs = chapter_text.split("\n\n")
        for para_text in paragraphs:
            para_text = para_text.strip()
            if not para_text:
                continue

            # Handle scene breaks
            if para_text in ("***", "* * *", "---", "- - -"):
                scene_break = doc.add_paragraph()
                scene_break.alignment = WD_ALIGN_PARAGRAPH.CENTER
                run = scene_break.add_run("* * *")
                run.font.size = Pt(14)
                run.font.color.rgb = RGBColor(0xBD, 0xBD, 0xBD)
                continue

            para = doc.add_paragraph(para_text)
            para.paragraph_format.first_line_indent = Inches(0.5)

        word_count = len(chapter_text.split())
        total_words += word_count

    # ── Save ──────────────────────────────────────────────────────────────
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"novel_{timestamp}.docx"
    filepath = out_dir / filename

    doc.save(str(filepath))

    logger.info(
        "[EXPORT] Saved: %s (%d chapters, %d words)",
        filepath, len(chapters), total_words,
    )
    return filepath
